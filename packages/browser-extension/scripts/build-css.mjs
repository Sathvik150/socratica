// Compiles the stylesheets in styles/ with the Tailwind CLI (see DESIGN.md):
//   styles/pages.css   -> static/theme.css               (popup, settings, demo)
//   styles/overlay.css -> src/ui/overlay.generated.ts    (Shadow DOM overlay, CSS as a string)
import { execFileSync } from 'node:child_process';
import { readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const styles = join(root, 'styles');

const cli = join(dirname(createRequire(import.meta.url).resolve('@tailwindcss/cli/package.json')), 'dist/index.mjs');
const tailwind = (input, output) =>
  execFileSync(process.execPath, [cli, '-i', input, '-o', output, '--minify'], { cwd: root, stdio: ['ignore', 'ignore', 'inherit'] });

tailwind(join(styles, 'pages.css'), join(root, 'static/theme.css'));

const tmp = join(root, 'src/ui/.overlay.tmp.css');
tailwind(join(styles, 'overlay.css'), tmp);
let css = readFileSync(tmp, 'utf8');
rmSync(tmp);
// Chrome ignores @property inside a shadow root, so Tailwind's registered defaults (e.g.
// --tw-border-style: solid) would be missing and borders would vanish. Declare them directly.
const defaults = [...css.matchAll(/@property\s+(--[\w-]+)\s*\{([^}]*)\}/g)]
  .map(([, name, body]) => `${name}:${/initial-value:\s*([^;}]+)/.exec(body)?.[1]?.trim() ?? 'initial'}`);
if (defaults.length) css = `@layer properties{*,:before,:after,::backdrop{${defaults.join(';')}}}\n${css}`;
writeFileSync(
  join(root, 'src/ui/overlay.generated.ts'),
  `// Generated by scripts/build-css.mjs from styles/overlay.css (Tailwind CSS). Do not edit; run \`pnpm build:css\`.\nconst css = ${JSON.stringify(css)};\nexport default css;\n`,
);
console.log(`theme.css and overlay CSS (${(css.length / 1024).toFixed(1)} KB) built with Tailwind.`);
